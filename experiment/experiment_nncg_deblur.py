"""Matrix-free 2-D image deblurring for "Non-Negative Conjugate Gradients".

Demonstrates the matrix-free operator abstraction (Section 3) at a scale where
the Gram matrix cannot be formed. A separable Gaussian blur B = K (x) K acts
on an N-by-N image (n = N^2 unknowns); applied as X -> K X K^T it costs O(N^3)
per product and never materialises the n-by-n operator A = B^T B, whose dense
storage would be O(n^2). Images are non-negative, so the reconstruction is a
non-negative least-squares problem, solved by the matrix-free active-set loop
(solve_nnqp_op) with a ridge split for the P-matrix property.

At N = 128 the operator has n = 16384 unknowns; a dense A would need ~2 GB,
yet the matrix-free loop runs in O(n) working memory. This is the regime the
companion papers target and the reason to keep a Krylov inner solve.

Usage:
    uv run experiment_nncg_deblur.py   # from non_negative_cg/experiment/

Outputs:
    graphs/nncg_deblur.pdf        true / blurred+noise / reconstructed panels
    tables/nncg_deblur_defs.tex   headline numbers as \\newcommand macros

The solve is NumPy only; matplotlib is used solely to render the figure.
"""

# /// script
# requires-python = ">=3.11"
# dependencies = ["matplotlib", "numpy"]
# ///

from __future__ import annotations

import time
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np

from util.runner import output_dirs

from nncg_ref import solve_nnqp_op

HERE = Path(__file__).parent
GRAPHS, TABLES = output_dirs(HERE)

mpl.rcParams.update({"font.family": "serif", "font.size": 9,
                     "axes.titlesize": 9, "figure.dpi": 150})


def gaussian_blur(nside, sigma):
    """Row-normalised 1-D Gaussian Toeplitz blur; the 2-D blur is K (x) K."""
    i = np.arange(nside)
    d = np.abs(np.subtract.outer(i, i))
    K = np.exp(-(d ** 2) / (2.0 * sigma ** 2))
    return K / K.sum(axis=1, keepdims=True)


def test_image(nside):
    """A non-negative test scene: two squares of different intensity and a disk."""
    X = np.zeros((nside, nside))
    q = nside // 8
    X[q:3 * q, q:3 * q] = 1.0
    X[5 * q:7 * q, 5 * q:7 * q] = 0.6
    ii, jj = np.mgrid[0:nside, 0:nside]
    X[(ii - nside // 2) ** 2 + (jj - 3 * nside // 4) ** 2 < (nside // 10) ** 2] = 0.8
    return X


NSIDE = 128
SIGMA = 2.0
ALPHA = 1e-3                                          # ridge split weight
NOISE_REL = 1e-3

n = NSIDE * NSIDE
K = gaussian_blur(NSIDE, SIGMA)
X_true = test_image(NSIDE)
x_true = X_true.ravel()

D = K @ X_true @ K.T                                  # blurred image, B x
rng = np.random.default_rng(0)
D_noisy = D + NOISE_REL * np.linalg.norm(D) * rng.standard_normal((NSIDE, NSIDE)) / NSIDE


def matvec(xv):
    """A_alpha x = (1-alpha) B^T B x + alpha x, matrix-free via K X K^T."""
    Xm = xv.reshape(NSIDE, NSIDE)
    Y = K @ Xm @ K.T                                  # B x
    Z = K.T @ Y @ K                                   # B^T (B x)
    return (1.0 - ALPHA) * Z.ravel() + ALPHA * xv     # ridge target R^T R = I


b = (K.T @ D_noisy @ K).ravel()                       # B^T d

print("=" * 70)
print(f"Matrix-free 2-D deblurring: {NSIDE}x{NSIDE} image, n = {n} unknowns")
print(f"sigma = {SIGMA}, ridge alpha = {ALPHA:.0e}, noise = {NOISE_REL:.0e}")
print("=" * 70)

t0 = time.perf_counter()
res = solve_nnqp_op(matvec, b, cg_tol=1e-8, cg_maxit=500, max_outer=40)
dt = time.perf_counter() - t0

x = res["x"]
active = int(np.sum(x <= 1e-8))
recov = float(np.max(np.abs(x - x_true)))
dense_gb = (n * n * 8) / 1e9

print(f"converged      : {res['converged']}")
print(f"outer steps    : {res['outer']}")
print(f"CG inner total : {res['inner']}")
print(f"active (bound)  : {active} of {n}")
print(f"recovery |x-x*| : {recov:.2e}")
print(f"wall-clock      : {dt:.2f} s")
print(f"dense A would be: {dense_gb:.1f} GB (never formed)")

# ---------------------------------------------------------------------------
# Figure: true / blurred+noise / reconstructed
# ---------------------------------------------------------------------------

X_hat = x.reshape(NSIDE, NSIDE)
panels = [("True $x^\\star$", X_true),
          ("Blurred $+$ noise", D_noisy),
          ("Reconstructed (NNCG)", X_hat)]
vmax = float(X_true.max())
fig, axes = plt.subplots(1, 3, figsize=(6.6, 2.4))
for ax, (title, img) in zip(axes, panels):
    ax.imshow(img, cmap="gray", vmin=0.0, vmax=vmax, interpolation="nearest")
    ax.set_title(title)
    ax.set_xticks([])
    ax.set_yticks([])
fig.tight_layout(pad=0.6)
fig.savefig(GRAPHS / "nncg_deblur.pdf", bbox_inches="tight")
fig.savefig(GRAPHS / "nncg_deblur.png", bbox_inches="tight", dpi=150)
print(f"Saved {GRAPHS / 'nncg_deblur.pdf'}")

with open(TABLES / "nncg_deblur_defs.tex", "w") as fh:
    fh.write("% Generated by experiment_nncg_deblur.py -- do not edit by hand.\n")
    fh.write(f"\\newcommand{{\\nncgDeblurNside}}{{{NSIDE}}}\n")
    fh.write(f"\\newcommand{{\\nncgDeblurDim}}{{{n}}}\n")
    fh.write(f"\\newcommand{{\\nncgDeblurOuter}}{{{res['outer']}}}\n")
    fh.write(f"\\newcommand{{\\nncgDeblurInner}}{{{res['inner']}}}\n")
    fh.write(f"\\newcommand{{\\nncgDeblurActive}}{{{active}}}\n")
    fh.write(f"\\newcommand{{\\nncgDeblurDenseGB}}{{{dense_gb:.1f}}}\n")
print(f"\nSaved {TABLES / 'nncg_deblur_defs.tex'}")
